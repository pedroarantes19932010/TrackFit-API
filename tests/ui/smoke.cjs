// Run after serving android/app/src/main/assets at localhost:8765.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||undefined,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765');
 await page.getByRole('button',{name:'Conhecer a demonstração'}).click();
 await page.getByRole('heading',{name:'Olá, Pedro.'}).waitFor();
 await page.screenshot({path:'/tmp/trackfit-trainer.png',fullPage:true});
 await page.getByRole('button',{name:'Abrir ficha'}).click();
 await page.getByRole('button',{name:'Editar ficha completa'}).click();
 await page.locator('#title0').fill('Treino revisado');
 await page.locator('#note').fill('Ajustei o título após avaliação');
 await page.getByRole('button',{name:'Salvar e liberar versão revisada'}).click();
 await page.getByRole('heading',{name:'Treino revisado'}).waitFor();
 await page.locator('#homeNav').click();
 await page.getByRole('button',{name:'Ver como aluno'}).click();
 await page.getByRole('button',{name:'Abrir ficha'}).click();
 await page.getByRole('button',{name:'Iniciar treino'}).click();
 await page.locator('.weight').first().fill('12,5');
 await page.locator('.reps').first().fill('10');
 await page.getByRole('button',{name:'Salvar treino realizado'}).click();
 await page.getByRole('heading',{name:'Histórico de treinos.'}).waitFor();
 await page.getByRole('button',{name:'Abrir registro'}).click();
 assert.equal(await page.locator('.weight').first().inputValue(),'12.5');
 await page.locator('#newNav').click();
 await page.screenshot({path:'/tmp/trackfit-assessment.png',fullPage:true});
 await page.locator('#age').fill('30');
 await page.locator('#review').selectOption('yes');
 await page.locator('#consent').check();
 await page.getByRole('button',{name:'Solicitar ficha completa'}).click();
 await page.getByText('Aguardando avaliação',{exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Iniciar treino'}).count(),0);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('PASS: offline trainer review, student training log, pending assessment, mobile layout; no JS errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
